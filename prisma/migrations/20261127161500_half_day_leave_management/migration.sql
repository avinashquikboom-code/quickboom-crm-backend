-- Half-Day Leave Management fields
ALTER TABLE "Attendance"
  ADD COLUMN IF NOT EXISTS "isHalfDayLeave" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "halfDaySession" TEXT,
  ADD COLUMN IF NOT EXISTS "leaveRequestId" INTEGER;

ALTER TABLE "LeaveRequest"
  ALTER COLUMN "days" TYPE DOUBLE PRECISION USING "days"::DOUBLE PRECISION,
  ALTER COLUMN "days" SET DEFAULT 1.0,
  ADD COLUMN IF NOT EXISTS "durationType" TEXT NOT NULL DEFAULT 'FULL_DAY',
  ADD COLUMN IF NOT EXISTS "halfDaySession" TEXT,
  ADD COLUMN IF NOT EXISTS "shiftId" INTEGER,
  ADD COLUMN IF NOT EXISTS "shiftStartTime" TEXT,
  ADD COLUMN IF NOT EXISTS "shiftEndTime" TEXT,
  ADD COLUMN IF NOT EXISTS "halfStartTime" TEXT,
  ADD COLUMN IF NOT EXISTS "halfEndTime" TEXT,
  ADD COLUMN IF NOT EXISTS "leaveHours" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "workingHours" DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS "applicationDeadline" TIMESTAMP(3),
  ADD COLUMN IF NOT EXISTS "isExceptional" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "exceptionalReason" TEXT,
  ADD COLUMN IF NOT EXISTS "approvedAt" TIMESTAMP(3),
  ADD COLUMN IF NOT EXISTS "cancelledAt" TIMESTAMP(3);

ALTER TABLE "LeavePolicy"
  ADD COLUMN IF NOT EXISTS "sameDaySecondHalfCutoffHours" DOUBLE PRECISION NOT NULL DEFAULT 2.0,
  ADD COLUMN IF NOT EXISTS "requireFirstHalfPunchInForSameDaySecondHalf" BOOLEAN NOT NULL DEFAULT true;
