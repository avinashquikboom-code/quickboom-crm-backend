import PDFDocument = require('pdfkit');

export interface PlanProposalPdfData {
  proposalNo: string;
  leadName: string;
  companyName: string;
  planName: string;
  planPrice: number;
  currency?: string;
  proposalType: string;
  features?: string[];
  customerRequirements?: string;
  discount?: number;
  validUntil?: string;
  terms?: string;
  customSummary?: string;
}

export async function generatePlanProposalPdfBuffer(data: PlanProposalPdfData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 48, size: 'A4' });
    const chunks: Buffer[] = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.fontSize(20).fillColor('#163A2E').text('Plan Proposal', { align: 'center' });
    doc.moveDown(0.5);
    doc.fontSize(10).fillColor('#64748B').text(`Reference: ${data.proposalNo}`, { align: 'center' });
    doc.moveDown(1.2);

    doc.fontSize(12).fillColor('#0f172a').text(`Prepared for: ${data.leadName}`);
    if (data.companyName) {
      doc.text(`Business: ${data.companyName}`);
    }
    doc.moveDown(0.8);

    doc.fontSize(14).fillColor('#163A2E').text(data.planName);
    doc.fontSize(11).fillColor('#0f172a').text(
      `Type: ${data.proposalType}  •  Price: ${data.currency || 'INR'} ${Number(data.planPrice || 0).toLocaleString('en-IN')}`,
    );
    if (data.discount) {
      doc.text(`Discount applied: ${data.currency || 'INR'} ${Number(data.discount).toLocaleString('en-IN')}`);
    }
  if (data.validUntil) {
      doc.text(`Valid until: ${data.validUntil}`);
    }
    doc.moveDown(0.8);

    if (data.customerRequirements) {
      doc.fontSize(12).fillColor('#163A2E').text('Customer requirements');
      doc.fontSize(10).fillColor('#334155').text(data.customerRequirements, { align: 'left' });
      doc.moveDown(0.6);
    }

    const features = data.features || [];
    if (features.length) {
      doc.fontSize(12).fillColor('#163A2E').text('Included features');
      doc.fontSize(10).fillColor('#334155');
      features.forEach((item) => doc.text(`• ${item}`));
      doc.moveDown(0.6);
    }

    if (data.customSummary) {
      doc.fontSize(12).fillColor('#163A2E').text('Custom package');
      doc.fontSize(10).fillColor('#334155').text(data.customSummary);
      doc.moveDown(0.6);
    }

    if (data.terms) {
      doc.fontSize(12).fillColor('#163A2E').text('Terms & conditions');
      doc.fontSize(10).fillColor('#334155').text(data.terms);
    }

    doc.moveDown(1.5);
    doc.fontSize(9).fillColor('#94a3b8').text('Generated by QB Suite CRM', { align: 'center' });

    doc.end();
  });
}
